// Command traceability maps tests to spec requirement IDs [NFR-22]. Tests declare the
// IDs they cover in a "// Covers: API-01, RTE-06" comment directly above the test.
// It writes docs/TRACEABILITY.md and exits non-zero if -strict and any MUST is uncovered.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var (
	reqRow   = regexp.MustCompile(`^\|\s*([A-Z]{3}-\d{2})\s*\|(.*)\|\s*(MUST|SHOULD|COULD)\s*\|\s*$`)
	nfrRow   = regexp.MustCompile(`^\|\s*(NFR-\d{2})\s*\|\s*([^|]+)\|\s*([^|]+)\|`)
	covers   = regexp.MustCompile(`(?://|#)\s*Covers:\s*(.+)$`)
	idRe     = regexp.MustCompile(`[A-Z]{3}-\d{2}`)
	testFunc = regexp.MustCompile(`^func (Test\w+|Benchmark\w+)\(`)
	pyFunc   = regexp.MustCompile(`^def (\w+)\(`)
)

type req struct {
	ID, Text, Priority string
}

func main() {
	spec := flag.String("spec", "docs/SPEC.md", "spec file")
	out := flag.String("out", "docs/TRACEABILITY.md", "output file")
	strict := flag.Bool("strict", false, "fail if a MUST requirement has no test")
	flag.Parse()

	reqs, err := parseSpec(*spec)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(2)
	}
	cov := map[string][]string{}
	_ = filepath.Walk(".", func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() && (info.Name() == ".git" || info.Name() == "node_modules") {
			if info != nil && info.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		if strings.HasSuffix(path, "_test.go") || (strings.HasPrefix(path, "scenarios") && strings.HasSuffix(path, ".py")) || strings.HasPrefix(path, "suites") {
			scanFile(path, cov)
		}
		return nil
	})

	var b strings.Builder
	b.WriteString("# Requirement traceability\n\nGenerated by `go run ./cmd/traceability`. Each row lists the automated tests that declare `Covers: <ID>`.\n\n")
	var mustTotal, mustCovered int
	var uncovered []string
	b.WriteString("| ID | Priority | Requirement | Tests |\n| --- | --- | --- | --- |\n")
	for _, r := range reqs {
		tests := cov[r.ID]
		sort.Strings(tests)
		if r.Priority == "MUST" {
			mustTotal++
			if len(tests) > 0 {
				mustCovered++
			} else {
				uncovered = append(uncovered, r.ID)
			}
		}
		cell := "—"
		if len(tests) > 0 {
			cell = "`" + strings.Join(dedupe(tests), "`, `") + "`"
		}
		text := r.Text
		if len(text) > 90 {
			text = text[:87] + "..."
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", r.ID, r.Priority, strings.ReplaceAll(text, "|", "\\|"), cell)
	}
	fmt.Fprintf(&b, "\n**MUST coverage: %d / %d**", mustCovered, mustTotal)
	if len(uncovered) > 0 {
		fmt.Fprintf(&b, " — uncovered: %s", strings.Join(uncovered, ", "))
	}
	b.WriteString("\n")
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(2)
	}
	fmt.Printf("MUST coverage %d/%d\n", mustCovered, mustTotal)
	if *strict && len(uncovered) > 0 {
		fmt.Println("uncovered:", strings.Join(uncovered, ", "))
		os.Exit(1)
	}
}

func dedupe(s []string) []string {
	var out []string
	for i, v := range s {
		if i == 0 || v != s[i-1] {
			out = append(out, v)
		}
	}
	return out
}

func parseSpec(path string) ([]req, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var reqs []req
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		if m := reqRow.FindStringSubmatch(line); m != nil {
			reqs = append(reqs, req{ID: m[1], Text: strings.TrimSpace(m[2]), Priority: m[3]})
		} else if m := nfrRow.FindStringSubmatch(line); m != nil {
			// NFRs have no priority column; they are all release criteria (MUST).
			reqs = append(reqs, req{ID: m[1], Text: strings.TrimSpace(m[3]), Priority: "MUST"})
		}
	}
	return reqs, sc.Err()
}

func scanFile(path string, cov map[string][]string) {
	f, err := os.Open(path)
	if err != nil {
		return
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	var pending []string
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if m := covers.FindStringSubmatch(line); m != nil {
			pending = append(pending, idRe.FindAllString(m[1], -1)...)
			continue
		}
		name := ""
		if m := testFunc.FindStringSubmatch(line); m != nil {
			name = m[1]
		} else if m := pyFunc.FindStringSubmatch(line); m != nil {
			name = filepath.Base(path) + ":" + m[1]
		}
		if name != "" && len(pending) > 0 {
			for _, id := range pending {
				cov[id] = append(cov[id], name)
			}
			pending = nil
		}
	}
}
