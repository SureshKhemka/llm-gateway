// Command traceability maps tests to spec requirement IDs [NFR-22]. Tests declare the
// IDs they cover in a "// Covers: API-01, RTE-06" comment directly above the test.
// It writes docs/TRACEABILITY.md and exits non-zero if -strict and any MUST is uncovered.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var (
	reqRow   = regexp.MustCompile(`^\|\s*([A-Z]{3}-\d{2})\s*\|(.*)\|\s*(MUST|SHOULD|COULD)\s*\|\s*$`)
	nfrRow   = regexp.MustCompile(`^\|\s*(NFR-\d{2})\s*\|\s*([^|]+)\|\s*([^|]+)\|`)
	covers   = regexp.MustCompile(`(?://|#)\s*Covers:\s*(.+)$`)
	idRe     = regexp.MustCompile(`[A-Z]{3}-\d{2}`)
	testFunc = regexp.MustCompile(`^func (Test\w+|Benchmark\w+)\(`)
	pyFunc   = regexp.MustCompile(`^def (\w+)\(`)
)

type req struct {
	ID, Text, Priority string
}

func main() {
	spec := flag.String("spec", "docs/SPEC.md", "spec file")
	out := flag.String("out", "docs/TRACEABILITY.md", "output file")
	strict := flag.Bool("strict", false, "fail if a MUST requirement has no test")
	flag.Parse()

	r, err := build(".", *spec)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(2)
	}
	if err := os.WriteFile(*out, []byte(r.markdown), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(2)
	}
	fmt.Printf("MUST coverage %d/%d\n", r.mustCovered, r.mustTotal)
	if *strict && (len(r.uncovered) > 0 || len(r.untagged) > 0) {
		fmt.Println("uncovered:", strings.Join(r.uncovered, ", "))
		fmt.Println("tests without Covers:", strings.Join(r.untagged, ", "))
		os.Exit(1)
	}
}

type report struct {
	markdown               string
	mustTotal, mustCovered int
	uncovered              []string // MUST IDs with no test
	untagged               []string // tests with no Covers line
	unknown                []string // Covers IDs that aren't in the spec
}

func build(root, spec string) (*report, error) {
	reqs, err := parseSpec(filepath.Join(root, spec))
	if err != nil {
		return nil, err
	}
	cov := map[string][]string{}
	r := &report{}
	_ = filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() && (info.Name() == ".git" || info.Name() == "node_modules") {
			if info != nil && info.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		rel, _ := filepath.Rel(root, path)
		if strings.HasSuffix(rel, "_test.go") || (strings.HasPrefix(rel, "scenarios") && strings.HasSuffix(rel, ".py")) || strings.HasPrefix(rel, "suites") {
			r.untagged = append(r.untagged, scanFile(path, cov)...)
		}
		return nil
	})
	known := map[string]bool{}
	for _, q := range reqs {
		known[q.ID] = true
	}
	for id := range cov {
		if !known[id] {
			r.unknown = append(r.unknown, id)
		}
	}
	sort.Strings(r.unknown)

	var b strings.Builder
	b.WriteString("# Requirement traceability\n\nGenerated by `go run ./cmd/traceability`. Each row lists the automated tests that declare `Covers: <ID>`.\n\n")
	b.WriteString("| ID | Priority | Requirement | Tests |\n| --- | --- | --- | --- |\n")
	for _, q := range reqs {
		tests := cov[q.ID]
		sort.Strings(tests)
		if q.Priority == "MUST" {
			r.mustTotal++
			if len(tests) > 0 {
				r.mustCovered++
			} else {
				r.uncovered = append(r.uncovered, q.ID)
			}
		}
		cell := "—"
		if len(tests) > 0 {
			cell = "`" + strings.Join(dedupe(tests), "`, `") + "`"
		}
		text := q.Text
		if len(text) > 90 {
			text = text[:87] + "..."
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", q.ID, q.Priority, strings.ReplaceAll(text, "|", "\\|"), cell)
	}
	fmt.Fprintf(&b, "\n**MUST coverage: %d / %d**", r.mustCovered, r.mustTotal)
	if len(r.uncovered) > 0 {
		fmt.Fprintf(&b, " — uncovered: %s", strings.Join(r.uncovered, ", "))
	}
	b.WriteString("\n")
	r.markdown = b.String()
	return r, nil
}

func dedupe(s []string) []string {
	var out []string
	for i, v := range s {
		if i == 0 || v != s[i-1] {
			out = append(out, v)
		}
	}
	return out
}

func parseSpec(path string) ([]req, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var reqs []req
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		if m := reqRow.FindStringSubmatch(line); m != nil {
			reqs = append(reqs, req{ID: m[1], Text: strings.TrimSpace(m[2]), Priority: m[3]})
		} else if m := nfrRow.FindStringSubmatch(line); m != nil {
			// NFRs have no priority column; they are all release criteria (MUST).
			reqs = append(reqs, req{ID: m[1], Text: strings.TrimSpace(m[3]), Priority: "MUST"})
		}
	}
	return reqs, sc.Err()
}

// scanFile records Covers IDs per test and returns the tests that have none.
func scanFile(path string, cov map[string][]string) (untagged []string) {
	f, err := os.Open(path)
	if err != nil {
		return nil
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	var pending []string
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if m := covers.FindStringSubmatch(line); m != nil {
			pending = append(pending, idRe.FindAllString(m[1], -1)...)
			continue
		}
		name := ""
		if m := testFunc.FindStringSubmatch(line); m != nil {
			name = m[1]
		} else if m := pyFunc.FindStringSubmatch(line); m != nil {
			name = filepath.Base(path) + ":" + m[1]
		}
		if name != "" && len(pending) > 0 {
			for _, id := range pending {
				cov[id] = append(cov[id], name)
			}
			pending = nil
		} else if name != "" && (strings.HasPrefix(name, "Test") || strings.Contains(name, ":test_")) {
			untagged = append(untagged, path+":"+name)
		}
	}
	return untagged
}
